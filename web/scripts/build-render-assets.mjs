/*
 * Builds the stylesheets the paper is rendered with, and copies them to the render
 * service so both sides print from identical bytes.
 *
 * Fonts are inlined as base64. The alternative — serving font files to the headless
 * browser — needs the printer to have network or filesystem access to something the
 * preview also has, and any gap there shows up as a different typeface, different line
 * breaks, and a PDF that does not match what the user approved. Inlining costs about
 * 180 KB in the payload and removes the failure mode entirely.
 *
 * Run: npm run build:render-assets
 */
import { readFile, writeFile, mkdir, readdir } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const web = resolve(here, '..');
const renderAssets = resolve(web, '../api/CvMakerPro.Render/Assets');

/*
 * Weight-axis-only files, latin subset. The optical-size and full-unicode builds are
 * two to four times larger and neither earns it: CVs are latin text at one or two sizes.
 */
const FONTS = [
  {
    family: 'Source Serif 4 Variable',
    file: '@fontsource-variable/source-serif-4/files/source-serif-4-latin-wght-normal.woff2',
    weight: '200 900',
    style: 'normal',
  },
  {
    family: 'Source Serif 4 Variable',
    file: '@fontsource-variable/source-serif-4/files/source-serif-4-latin-wght-italic.woff2',
    weight: '200 900',
    style: 'italic',
  },
  {
    family: 'Instrument Sans Variable',
    file: '@fontsource-variable/instrument-sans/files/instrument-sans-latin-wght-normal.woff2',
    weight: '400 700',
    style: 'normal',
  },
  {
    family: 'Instrument Sans Variable',
    file: '@fontsource-variable/instrument-sans/files/instrument-sans-latin-wght-italic.woff2',
    weight: '400 700',
    style: 'italic',
  },
];

async function buildFontCss() {
  const faces = await Promise.all(
    FONTS.map(async ({ family, file, weight, style }) => {
      const bytes = await readFile(join(web, 'node_modules', file));
      return [
        '@font-face {',
        `  font-family: '${family}';`,
        `  font-style: ${style};`,
        `  font-weight: ${weight};`,
        // Block rather than swap: a fallback face rendered for even one frame during the
        // measuring pass produces heights for the wrong font, and the page count is wrong.
        '  font-display: block;',
        `  src: url(data:font/woff2;base64,${bytes.toString('base64')}) format('woff2');`,
        '}',
      ].join('\n');
    }),
  );

  return `/* Generated by scripts/build-render-assets.mjs — do not edit. */\n${faces.join('\n\n')}\n`;
}

async function templateStylesheets() {
  const templatesDir = join(web, 'src/templates');
  const names = await readdir(templatesDir, { withFileTypes: true });
  const templates = [];

  for (const entry of names) {
    if (!entry.isDirectory()) continue;
    const css = join(templatesDir, entry.name, `${entry.name}.css`);
    templates.push({ id: entry.name, css: await readFile(css, 'utf8') });
  }

  return templates;
}

const fontCss = await buildFontCss();
const paperCss = await readFile(join(web, 'src/templates/paper.css'), 'utf8');
const templates = await templateStylesheets();

// One composed sheet per template, in the order both renderers use: fonts, paper, template.
await mkdir(join(renderAssets, 'templates'), { recursive: true });
await writeFile(join(web, 'src/generated/fonts.css'), fontCss);

for (const { id, css } of templates) {
  await writeFile(join(renderAssets, 'templates', `${id}.css`), [fontCss, paperCss, css].join('\n'));
}

console.log(
  `Wrote fonts.css (${(fontCss.length / 1024).toFixed(0)} KB) and ${templates.length} composed stylesheet(s): ${templates
    .map((template) => template.id)
    .join(', ')}`,
);
